const test = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
function setup() {
 const storage = () => { const values = new Map(); return {getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)}; };
 const context = {window:{},localStorage:storage(),sessionStorage:storage(),crypto:require('node:crypto').webcrypto,structuredClone};
 vm.runInNewContext(fs.readFileSync('js/data.js','utf8'),context);
 return {api:context.window.SchoolData,context};
}
test('roles, teacher lifecycle, activity ownership, permissions and persistence', async () => {
 const {api,context}=setup();
 await assert.rejects(api.listTeachers());
 await assert.rejects(api.login('admin','wrong'));
 await api.login('admin','1000000000');
 assert.equal((await api.listTeachers()).length,3);
 assert.ok(!(await api.listTeachers())[0].civilRegistration);
 const input={name:'معلمة اختبار',job:'علوم',civilRegistration:'1234567890',username:'test'};
 const id=await api.saveTeacher(input);
 await assert.rejects(api.saveTeacher(input));
 await api.saveTeacher({...input,job:'لغة عربية'},id);
 assert.equal((await api.getTeacher(id)).job,'لغة عربية');
 const payload={title:'نشاط تجريبي',type:'مبادرة',date:'2026-09-27',description:'وصف',notes:''};
 const a=await api.saveActivity({...payload,attachment:{name:'test.pdf',data:'data:application/pdf;base64,AA=='}},id);
 await api.saveActivity({...payload,attachment:null},id,a);
 assert.equal((await api.getActivity(a,id)).attachment,null);
 await assert.rejects(api.getActivity(a,'hana-ali'));
 await assert.rejects(api.deleteActivity(a,'hana-ali'));
 assert.equal((await api.listActivities(id)).length,1);
 await api.setTeacherActive(id,false);
 await assert.rejects(api.login('test','1234567890'));
 await assert.rejects(api.saveActivity(payload,id));
 await api.setTeacherActive(id,true);
 await api.login('test','١٢٣٤٥٦٧٨٩٠');
 await assert.rejects(api.listTeachers());
 await assert.rejects(api.listUsers());
 await assert.rejects(api.listActivities('hana-ali'));
 await assert.rejects(api.getTeacher('hana-ali'));
 await assert.rejects(api.getActivity(a,'hana-ali'));
 assert.equal((await api.listActivities(id)).length,1);
 assert.equal((await api.getActivity(a,id)).teacherId,id);
 assert.equal((await api.getTeacher(id)).civilRegistration,undefined);
 await assert.rejects(api.setAdmin('hana-ali',true));
 await assert.rejects(api.deleteActivity(a,id));
 await assert.rejects(api.saveActivity(payload,id,a));
 const own=await api.saveActivity(payload,'hana-ali');
 const stored=JSON.parse(context.localStorage.getItem('schoolAdminActivities'));
 assert.equal(stored.find(x=>x.id===own).teacherId,id);
 await api.logout(); assert.equal(await api.session(),null);
 await api.login('admin','1000000000');
 await api.setAdmin(id,true);
 await api.login('test','1234567890'); assert.equal((await api.session()).role,'admin');
 await assert.rejects(api.setAdmin(id,false));
 await api.login('admin','1000000000'); await api.setAdmin(id,false);
 await api.deleteActivity(a,id);
 assert.equal((await api.listActivities(id)).length,1);
 await api.createAdmin({name:'إدارية',job:'إدارة',username:'second',civilRegistration:'1111111111'});
 await api.login('second','1111111111'); assert.equal((await api.session()).role,'admin');
 await api.logout(); await api.login('admin','1000000000');
 const second=(await api.listUsers()).find(u=>u.username==='second');
 await api.setAdmin(second.id,false); await assert.rejects(api.login('second','1111111111'));
 await api.setAdmin(second.id,true); await api.login('second','1111111111');
 assert.equal((await api.session()).role,'admin');
 await api.login('admin','1000000000');
 vm.runInNewContext(fs.readFileSync('js/data.js','utf8'),context);
 assert.equal((await context.window.SchoolData.listTeachers()).length,4);
});
test('existing activities retained and invalid storage is not silently overwritten',async()=>{
 const {api,context}=setup();
 context.localStorage.setItem('schoolAdminActivities',JSON.stringify([{id:'legacy',teacherId:'noura-mohammed',title:'قديم'}]));
 await api.login('admin','1000000000'); assert.equal((await api.listActivities('noura-mohammed'))[0].id,'legacy');
 context.localStorage.setItem('schoolAdminActivities','broken');
 await assert.rejects(api.listActivities('noura-mohammed'));
 assert.equal(context.localStorage.getItem('schoolAdminActivities'),'broken');
});
